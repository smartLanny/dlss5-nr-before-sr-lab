#pragma once
#include <cstdint>
#include <cstdio>
#include <string>

// Portable, deterministic naming/content policy. No filesystem or GPU access.
namespace nr_feedback_single {
// Bounded metadata plus up to six independently bounded 24 KiB summaries and
// their framing. A full metadata report must not crowd out the current log.
constexpr std::size_t kTextLimit = 832u * 1024u;
inline std::string Component(std::string value, const char *fallback) {
    const auto slash = value.find_last_of("/\\");
    if (slash != std::string::npos) value.erase(0, slash + 1);
    std::string out;
    for (unsigned char c : value) {
        if (c >= 'A' && c <= 'Z') c = static_cast<unsigned char>(c + ('a' - 'A'));
        const bool legal = (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '.' || c == '-';
        if (legal) out += static_cast<char>(c);
        else if (!out.empty() && out.back() != '-') out += '-';
        if (out.size() == 64) break;
    }
    while (!out.empty() && (out.back() == '.' || out.back() == '-')) out.pop_back();
    if (out.empty() || out == "." || out == "..") out = fallback;
    return out;
}
inline std::string Filename(const std::string &exe, const std::string &build,
                           unsigned year, unsigned month, unsigned day,
                           unsigned hour, unsigned minute, unsigned second, unsigned millis,
                           unsigned long process, unsigned long long serial) {
    std::string game = Component(exe, "unknown-game");
    if (game.size() > 4 && game.compare(game.size() - 4, 4, ".exe") == 0) game.resize(game.size() - 4);
    const std::string version = Component(build, "unknown-version");
    char date[16]{}, suffix[80]{};
    std::snprintf(date, sizeof(date), "%02u%02u%02u", year % 100, month % 100, day % 100);
    std::snprintf(suffix, sizeof(suffix), "-%02u%02u%02u%03u-%lu-%llu.txt",
        hour % 100, minute % 100, second % 100, millis % 1000, process, serial);
    return std::string(date) + "-" + game + "-" + version + suffix;
}
inline bool SafeLeaf(const wchar_t *leaf) {
    if (!leaf || !*leaf) return false;
    std::size_t n = 0;
    for (; leaf[n]; ++n) {
        if (n >= 220 || !((leaf[n] >= L'a' && leaf[n] <= L'z') ||
            (leaf[n] >= L'A' && leaf[n] <= L'Z') || (leaf[n] >= L'0' && leaf[n] <= L'9') ||
            leaf[n] == L'.' || leaf[n] == L'-')) return false;
    }
    return n > 4 && std::wstring(leaf + n - 4) == L".txt" && leaf[0] != L'.';
}
struct Document {
    std::string text = "DLSS5 核心反馈 / Core feedback\n"
        "只需提交本 TXT；F7 图像为可选补充。No ZIP is generated by F8.\n"
        "format=DLSS5-CoreText-v2\nencoding=UTF-8\narchive.requested=0\n"
        "text.limitBytes=491520\n"
        "evidence.scope=bounded metadata and sanitized log excerpts, not unlimited raw logs\n"
        "diagnosis.scope=observations and next investigation steps; not a guaranteed root cause or repair\n";
    bool complete = true;
    unsigned optional_missing = 0;
    bool Append(const std::string &value) {
        constexpr std::size_t reserve = 512;
        if (text.size() > kTextLimit - reserve || value.size() > kTextLimit - reserve - text.size()) {
            complete = false; return false;
        }
        text += value; return true;
    }
    void Missing(const std::string &name, const char *reason, bool required) {
        if (required) complete = false;
        else ++optional_missing;
        Append("evidence." + name + "=missing; required=" + (required ? "1; " : "0; ") + reason + "\n");
    }
    void Finish() {
        text += "\ntext.optionalMissing=" + std::to_string(optional_missing) + "\n";
        text += complete ? "text.complete=1\n" : "text.complete=0\ntext.reason=required evidence missing, cancelled, changed, or budget exhausted\n";
        text += "END DLSS5 FEEDBACK TEXT\n";
    }
};
} // namespace nr_feedback_single
