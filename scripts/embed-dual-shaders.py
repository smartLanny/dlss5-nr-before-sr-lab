#!/usr/bin/env python3
"""Reproduce the second-pass downsample and the actual fused Core shader body."""
from pathlib import Path
import argparse

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
    root=Path(__file__).resolve().parents[1];src=root/'src'
    math=(src/'nr_dual_math.hlsli').read_text(encoding='utf-8')
    def expand(name):
        body=(src/name).read_text(encoding='utf-8');anchor='#include "nr_dual_math.hlsli"'
        if body.count(anchor)!=1:raise ValueError('Expected one model-domain math include')
        return body.replace(anchor,math)
    down=expand('nr_dual_downsample.hlsl');resolve=expand('nr_dual_resolve_cached.hlsli');residual=expand('nr_dual_residual.hlsl')
    outputs={src/'nr_dual_embedded.hpp': '#pragma once\n// Generated by scripts/embed-dual-shaders.py; do not edit.\nnamespace nr_dual::dx12::embedded {\ninline constexpr char downsample[] = R"NR_DUAL_SHADER('+down+')NR_DUAL_SHADER";\ninline constexpr char residual[] = R"NR_DUAL_SHADER('+residual+')NR_DUAL_SHADER";\n}\n'}
    path=src/'nr_before_sr.cpp';core=path.read_text(encoding='utf-8')
    begin='// DUAL_RESOLVE_EMBEDDED_BEGIN\n';end='// DUAL_RESOLVE_EMBEDDED_END'
    if core.count(begin)!=1 or core.count(end)!=1:raise ValueError('Actual production shader marker missing/duplicated')
    body='#define NR_DUAL_MAIN NeuralColor\n#define NR_DUAL_LOW_IN DualLowInput\n#define NR_DUAL_LOW_OUT DualLowOutput\n#define NR_DUAL_DELTA DualLowValidity\n'+resolve+'\n'
    outputs[path]=core.split(begin)[0]+begin+body+end+core.split(end)[1]
    for path,expected in outputs.items():
        if a.check:
            if path.read_text(encoding='utf-8')!=expected:raise ValueError('Embedded shader differs: '+path.name)
        else:path.write_text(expected,encoding='utf-8',newline='\n')
    print('Dual shader embeddings match' if a.check else 'Dual shader embeddings regenerated')
if __name__=='__main__':main()
