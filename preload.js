'use strict';

const { contextBridge, ipcRenderer, webUtils } = require('electron');

const invoke = (name, ...args) => ipcRenderer.invoke(name, ...args);
contextBridge.exposeInMainWorld('manager', Object.freeze({
  startupReady: () => ipcRenderer.send('startup-renderer-ready'),
  startupFailed: message => ipcRenderer.send('startup-renderer-failed', String(message || '').slice(0, 500)),
  exportStartupDiagnostic: () => invoke('startup-export'),
  boot: () => invoke('boot'),
  refresh: () => invoke('games-refresh'),
  listGames: () => invoke('games-list'),
  pickGame: () => invoke('pick-game'),
  pickExecutable: () => invoke('pick-executable'),
  pickAddon: () => invoke('pick-addon'),
  pickScanFolder: () => invoke('pick-scan-folder'),
  install: (id, options) => invoke('game-install', id, options),
  launch: id => invoke('game-launch', id),
  repair: (id, options) => invoke('game-repair', id, options),
  upgradeAddon: (id, version, options) => invoke('game-upgrade-addon', id, version, options),
  dismissGame: id => invoke('game-dismiss', id),
  renameGame: (id, name) => invoke('game-rename', id, name),
  setGameApi: (id, api, options) => invoke('game-api-set', id, api, options),
  applyGameRoute: (id, options) => invoke('game-route-apply', id, options),
  toggleD3D12: (id, enabled, options) => invoke('game-toggle-d3d12', id, enabled, options),
  uninstall: (id, removeSettings = false) => invoke('game-uninstall', id, removeSettings),
  diagnose: id => invoke('game-diagnose', id),
  buildFeedback: (id, options = {}) => invoke('feedback-build', id, options),
  exportFeedback: (id, options = {}) => invoke('feedback-export', id, options),
  readNr: id => invoke('nr-read', id),
  writeNr: (id, patch) => invoke('nr-write', id, patch),
  readSrModel: id => invoke('sr-model-read', id),
  writeSrModel: (id, selection) => invoke('sr-model-write', id, selection),
  inspectLaunchSettings: id => invoke('launch-settings-inspect', id),
  updateLaunchSettings: (id, domain, request, options) => invoke('launch-settings-update', id, domain, request, options),
  resetAllLaunchSettings: id => invoke('launch-settings-reset-all', id),
  saveLaunchSettings: (id, domain, request) => invoke('launch-settings-save', id, domain, request),
  previewLaunchSettings: (id, domain, request) => invoke('launch-settings-preview', id, domain, request),
  applyLaunchSettings: (planId, consent) => invoke('launch-settings-apply', planId, consent),
  restoreLaunchSettings: (id, domain) => invoke('launch-settings-restore', id, domain),
  recoverLaunchSettings: id => invoke('launch-settings-recover', id),
  prepareFgComponents: (id, options) => invoke('fg-components-prepare', id, options),
  restoreFgComponents: id => invoke('fg-components-restore', id),
  readReframework: id => invoke('game-reframework-inspect', id),
  prepareReframework: (id, options) => invoke('game-reframework-prepare', id, options),
  restoreReframework: id => invoke('game-reframework-restore', id),
  recoverReframework: id => invoke('game-reframework-recover', id),
  readHotkeys: id => invoke('game-hotkeys-read', id),
  writeHotkey: (id, target, binding) => invoke('game-hotkey-write', id, target, binding),
  restoreDefault: id => invoke('nr-default', id),
  recommended: id => invoke('nr-recommended', id),
  updateSettings: patch => invoke('settings-update', patch),
  listAddons: () => invoke('addon-list'),
  readPayloadSource: () => invoke('payload-source-read'),
  pickPayloadSource: () => invoke('payload-source-pick'),
  resetPayloadSource: () => invoke('payload-source-reset'),
  recheckPayloadSource: () => invoke('payload-source-recheck'),
  importAddon: file => invoke('addon-import', file),
  removeAddon: id => invoke('addon-remove', id),
  fetchGameArt: id => invoke('game-art', id),
  getGameIcon: (id, currentIcon) => invoke('game-icon', id, currentIcon),
  getExecutableIcon: file => invoke('game-selection-icon', file),
  confirmGame: selection => invoke('game-confirm', selection),
  pickGameIcon: () => invoke('pick-game-icon'),
  onAddonImported: callback => ipcRenderer.on('addon-imported', callback),
  onSrModelApplied: callback => ipcRenderer.on('sr-model-applied', (_event, payload) => callback(payload)),
  onLaunchSettingsApplied: callback => ipcRenderer.on('launch-settings-applied', (_event, payload) => callback(payload)),
  pathForFile: file => webUtils.getPathForFile(file),
  openExternal: key => invoke('open-external', key),
  openFolder: id => invoke('open-folder', id),
  copyText: text => invoke('copy-text', text),
  minimize: () => ipcRenderer.send('window-minimize'),
  close: () => ipcRenderer.send('window-close')
}));
